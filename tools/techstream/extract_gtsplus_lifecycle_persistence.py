def _operand(pe: Any, operand: Any) -> str:
    if hasattr(operand, "table"):
        resolved = resolve_token(pe, operand)
        if hasattr(resolved, "Method"):
            operand = resolved.Method.row
    text = format_operand(pe, operand)
    if " object at " in text:
        return "<generic-type>::" + text.split("::", 1)[1] if "::" in text else "<generic-token>"
    return text


