def _digest(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _relative(path: Path) -> str:
    return path.resolve().relative_to(REPO_ROOT.resolve()).as_posix()


def _sources(roots: dict[str, Path]) -> list[dict[str, Any]]:
    records = []
    main_manifest = json.loads((roots["recovered"] / "manifest.json").read_text())
    aux_manifest = json.loads((roots["aux"] / "manifest.json").read_text())
    for spec in INPUTS:
        path = roots[spec["root"]] / spec["relative"]
        data = path.read_bytes()
        if len(data) != spec["size"] or _digest(data) != spec["sha256"]:
            raise ValueError(f"source drift: {spec['id']}")
        record = {k: copy.deepcopy(v) for k, v in spec.items() if k not in ("root", "relative")}
        record["path"] = _relative(path)
        if spec["root"] == "recovered":
            row = next(x for x in main_manifest["binaries"] if x["path"] == spec["relative"])
            if row["plaintext"]["sha256"] != spec["sha256"] or not all(
                row["package_identity"][k] for k in ("cp_stub_matches_installed", "cp_sidecar_matches_installed")
            ):
                raise ValueError(f"installer-twin provenance drift: {spec['id']}")
            parents = {x["id"]: x for x in INPUTS if x["id"] in spec["derived_from"]}
            if {x["sha256"] for x in parents.values()} != {
                row["protected"]["stub_sha256"], row["protected"]["sidecar_sha256"]
            }:
                raise ValueError(f"protected source identity drift: {spec['id']}")
            record["recovery"]["manifest"] = _relative(roots["recovered"] / "manifest.json")
        elif spec["root"] == "aux":
            row = next(x for x in aux_manifest["entries"] if x["relative_path"] == spec["relative"])
            parents = {x["sha256"] for x in INPUTS if x["id"] in spec["derived_from"]}
            if row["output_sha256"] != spec["sha256"] or parents != {
                row["stub_sha256"], row["sidecar_sha256"]
            }:
                raise ValueError(f"auxiliary recovery provenance drift: {spec['id']}")
            record["recovery"] = {
                "command": "tools/gts recover-aux-bodies",
                "manifest": _relative(roots["aux"] / "manifest.json"),
            }
        records.append(record)
    return records


def _section(text: str, marker: str) -> str:
    if ".prototype." not in marker:
        return text
    start = text.index(marker)
    following = re.search(
        r"[A-Za-z_$][A-Za-z0-9_$]*\.prototype\.[A-Za-z0-9_$]+\s*=\s*function",
        text[start + len(marker):],
    )
    end = start + len(marker) + following.start() if following else len(text)
    return text[start:end]


