"""Ordered decompiler-body reconstruction pipeline."""
from __future__ import annotations

import re

from tools.targets.camry.decomp import abi, layout, runtime, syntax
from tools.targets.camry.decomp.conversion import rewrite_abi, rewrite_context, rewrite_memory, rewrite_pointer, rewrite_types




def _rewrite_body(code: str) -> str:
    code = re.sub(
        r"\b(?:u8|s8|u16|s16|u32|s32)\b",
        lambda match: layout._SCALAR_TYPES[match.group()], code,
    )
    code = rewrite_types._rewrite_firmware_pointer_arrays(code)
    code = rewrite_types._rewrite_firmware_pointer_records(code)
    code = rewrite_types._rewrite_inlined_mmio(code)
    code = rewrite_types._rewrite_protected_registers(code)
    code = rewrite_types._rewrite_numeric_record_types(code)
    code = rewrite_context._rewrite_paired_mpat_frame(code)
    code = rewrite_context._rewrite_paired_gpr_context(code)
    code = rewrite_pointer._rewrite_bitfields(code)
    code = rewrite_types._rewrite_packed_stack(code)
    code = re.sub(
        r"&stack0x([0-9a-fA-F]{8})\b",
        lambda match: abi._stack_local(code, int(match.group(1), 16) - 0x100000000) or match.group(0),
        code,
    )
    code = rewrite_types._rewrite_narrow_storage(code)
    code = syntax._strip_calling_convention(code)
    code = syntax._rewrite_thunk_calls(code)
    code = abi._widen_signature(code)
    code = rewrite_abi._rewrite_preserved_results(code)
    code = rewrite_abi._rewrite_recovered_arguments(code)
    code = rewrite_abi._rewrite_surviving_extraouts(code)
    code = rewrite_abi._rewrite_lost_arguments(code)
    code = rewrite_abi._rewrite_returned_call(code)
    code = rewrite_types._rewrite_merged_call_results(code)
    code = rewrite_abi._rewrite_saved_pmr(code)
    code = rewrite_abi._rewrite_stored_result(code)
    code = rewrite_abi._rewrite_held_result(code)
    code = rewrite_pointer._rewrite_firmware_bases(code)
    code = rewrite_types._rewrite_integer_temporaries(code)
    code = rewrite_memory._rewrite_ghidra_strings(code)
    signature = syntax._c_signature(code)
    pointers = syntax._pointer_names(signature, code)
    code = syntax._IDIOM.sub(r"((\1 < 0) || (\2 < 0))", code)
    code = rewrite_pointer._rewrite_indexed(code)
    code = rewrite_pointer._rewrite_addresses(code, pointers)
    code = rewrite_pointer._rewrite_device_pointer_add(code)
    code = rewrite_pointer._rewrite_symbol_indexes(code)
    code = rewrite_pointer._rewrite_explicit_fields(code)
    code = layout._rewrite_named_addresses(code, pointer_return=syntax._returns_pointer(signature))
    code = rewrite_pointer._rewrite_pointer_tables(code)
    code = rewrite_pointer._rewrite_pointer_to_int(code, pointers)
    code = rewrite_pointer._rewrite_int_to_pointer(code, pointers)
    code = rewrite_pointer._rewrite_pointer_calls(code, pointers)
    code = rewrite_pointer._rewrite_function_indexes(code)
    code = rewrite_pointer._rewrite_function_values(code)
    code = rewrite_pointer._rewrite_signed_byte_compares(code)
    code = rewrite_types._rewrite_struct_fields(code)
    code = rewrite_types._rewrite_pointer_assignments(code)
    code = rewrite_pointer._rewrite_indirect_calls(code)
    pointees = rewrite_memory._stored_pointer_pointees(code)
    code = rewrite_pointer._rewrite_pointer_compares(code, pointers)
    code = rewrite_pointer._rewrite_wide_call_constants(code)
    code = runtime._rewrite_eic(code)
    code = runtime._rewrite_icus(code)
    code = rewrite_memory._rewrite_nested_pointer_fields(code)
    code = rewrite_memory._rewrite_stored_pointer_loads(code, pointees)
    code = runtime._rewrite_runtime_gp(code)
    code = runtime._rewrite_signed_values(code)
    code = runtime._rewrite_system_inputs(code)
    code = rewrite_memory._rewrite_firmware_pointers(code)
    code = runtime._rewrite_runtime_tp(code)
    code = runtime._rewrite_scaled_table(code)
    code = rewrite_memory._rewrite_loaded_pointer_subscripts(code)
    code = rewrite_memory._rewrite_integer_subscripts(code)
    code = rewrite_memory._rewrite_loaded_word_indexes(code)
    code = rewrite_memory._rewrite_slot_word_uses(code)
    code = rewrite_memory._rewrite_pointer_word_indexes(code)
    code = rewrite_types._rewrite_late_pointer_fields(code)
    code = rewrite_types._rewrite_pointer_assignments(code, firmware=True)
    code = rewrite_types._rewrite_integer_arrows(code)
    code = rewrite_pointer._rewrite_signed_byte_compares(code)
    code = rewrite_memory._rewrite_dat_scalars(code)
    code = rewrite_memory._rewrite_address_parameters(code)
    code = rewrite_memory._rewrite_string_word_copies(code)
    code = rewrite_memory._rewrite_terminal_labels(code)
    code = rewrite_memory._rewrite_pointer_result(code)
    code = rewrite_types._rewrite_integer_temporaries(code)
    code = rewrite_pointer._rewrite_wide_call_constants(code)
    code = rewrite_types._rewrite_integer_address_derefs(code)
    code = rewrite_types._rewrite_loaded_pointer_words(code)
    code = rewrite_types._rewrite_pointer_macro_indexes(code)
    code = rewrite_types._rewrite_scalar_host_indexes(code)
    code = rewrite_types._rewrite_host_pointer_adds(code)
    code = rewrite_types._rewrite_mulhi_scales(code)
    code = rewrite_memory._rewrite_based_pointer_uses(code)
    code = rewrite_types._strip_assigned_pointer_casts(code, set())
    code = rewrite_pointer._rewrite_function_values(code)
    code = rewrite_types._rewrite_address_roundtrip(code)
    code = rewrite_types._retype_struct_address_words(code)
    code = rewrite_types._rewrite_pointer_assignments(code)
    code = rewrite_pointer._rewrite_pointer_compares(code, syntax._pointer_names(syntax._c_signature(code), code))
    code = rewrite_memory._rewrite_indirect_arguments(code)
    code = rewrite_pointer._rewrite_function_values(code)
    code = rewrite_context._rewrite_split_pointer_words(code)
    return rewrite_types._rewrite_inlined_mmio(code)
