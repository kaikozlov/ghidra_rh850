    private Set<String> pcodeOpNames(Instruction ins) {
        Set<String> ops = new HashSet<>();
        for (PcodeOp op : ins.getPcode()) {
            ops.add(op.getMnemonic());
        }
        return ops;
    }

    private String useropName(Instruction ins) {
        for (PcodeOp op : ins.getPcode()) {
            if (op.getOpcode() != PcodeOp.CALLOTHER) continue;
            int index = (int) op.getInput(0).getOffset();
            return currentProgram.getLanguage().getUserDefinedOpName(index);
        }
        return null;
    }

    private boolean hasSignExtendFromLoad(Instruction ins, int loadSize) {
        PcodeOp[] ops = ins.getPcode();
        for (int i = 0; i < ops.length; i++) {
            if (ops[i].getOpcode() == PcodeOp.LOAD) {
                // Look ahead for INT_SEXT using the load output.
                for (int j = i + 1; j < Math.min(ops.length, i + 4); j++) {
                    if (ops[j].getOpcode() == PcodeOp.INT_SEXT) return true;
                }
            }
        }
        // Some SLEIGH emits sext(*) as a single LOAD into a truncated temp then SEXT.
        Set<String> names = pcodeOpNames(ins);
        return names.contains("INT_SEXT");
    }

    private boolean hasZeroExtendFromLoad(Instruction ins) {
        return pcodeOpNames(ins).contains("INT_ZEXT");
    }

    private EmulatorHelper emulator(long pc) {
        EmulatorHelper emu = new EmulatorHelper(currentProgram);
        emu.writeRegister("PC", pc);
        return emu;
    }

    private void step(EmulatorHelper emu, String label) throws Exception {
        if (!emu.step(monitor)) {
            fail(label + ": emulator step failed: " + emu.getLastError());
        }
    }

    private void stepInterruptControl(EmulatorHelper emu, String label,
                                      String expectedUserop) throws Exception {
        if (emu.step(monitor)) return;
        String error = emu.getLastError();
        if (error == null || !error.contains(expectedUserop)) {
            fail(label + ": unexpected emulator failure: " + error);
        }
    }

    private void requireRegister(EmulatorHelper emu, String label,
                                 String register, long expected) {
        long actual = emu.readRegister(register).longValue() & 0xffffffffL;
        if (actual != (expected & 0xffffffffL)) {
            fail(String.format("%s: %s=0x%x expected=0x%x",
                    label, register, actual, expected & 0xffffffffL));
        }
    }

    private long readU32(EmulatorHelper emu, long address) {
        return ((long) emu.readMemoryByte(toAddr(address)) & 0xff)
                | (((long) emu.readMemoryByte(toAddr(address + 1)) & 0xff) << 8)
                | (((long) emu.readMemoryByte(toAddr(address + 2)) & 0xff) << 16)
                | (((long) emu.readMemoryByte(toAddr(address + 3)) & 0xff) << 24);
    }

    private long requireCaseAddr(java.util.Map<String, Long> addrs, String name) {
        Long addr = addrs.get(name);
        if (addr == null) {
            fail("execution vector missing fixture case: " + name);
            return -1;
        }
        return addr;
    }

    private boolean pswBit(EmulatorHelper emu, int bit) {
        return (emu.readRegister("PSW").longValue() & (1L << bit)) != 0;
    }

    private void verifyLdsr(java.util.Map<String, Long> addrs, String name,
                            String systemRegister, long value) throws Exception {
        long address = requireCaseAddr(addrs, name);
        if (address < 0) return;
        EmulatorHelper emu = emulator(address);
        try {
            emu.writeRegister("r6", value);
            step(emu, name);
            requireRegister(emu, name, systemRegister, value);
        } finally {
            emu.dispose();
        }
    }

